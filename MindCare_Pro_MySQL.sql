CREATE DATABASE IF NOT EXISTS mindcare_pro
    CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE mindcare_pro;

SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS AI_RESPONSE_RESOURCE_DOCUMENT;
DROP TABLE IF EXISTS CONSULTANT_RESOURCE_DOCUMENT;
DROP TABLE IF EXISTS AI_RESPONSE;
DROP TABLE IF EXISTS RESOURCE_DOCUMENT;
DROP TABLE IF EXISTS RESOURCE_QUERY;
DROP TABLE IF EXISTS FEEDBACK;
DROP TABLE IF EXISTS PRIVATE_NOTE;
DROP TABLE IF EXISTS CONSULTATION_SESSION;
DROP TABLE IF EXISTS UPLOADED_FILE;
DROP TABLE IF EXISTS PRECONSULTATION_FORM;
DROP TABLE IF EXISTS APPOINTMENT;
DROP TABLE IF EXISTS AVAILABILITY_SLOT;
DROP TABLE IF EXISTS CONSULTANT;
DROP TABLE IF EXISTS CLIENT;
DROP TABLE IF EXISTS PERSON_CONTACT;
DROP TABLE IF EXISTS PERSON;
SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE PERSON (
    PERSON_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    NAME VARCHAR(150) NOT NULL,
    EMAIL VARCHAR(255) NOT NULL,
    PASSWORD_HASH VARCHAR(255) NOT NULL,
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_PERSON PRIMARY KEY (PERSON_ID),
    CONSTRAINT UQ_PERSON_EMAIL UNIQUE (EMAIL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE PERSON_CONTACT (
    CONTACT_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    PERSON_ID BIGINT UNSIGNED NOT NULL,
    CONTACT_NO VARCHAR(30) NOT NULL,
    CONSTRAINT PK_PERSON_CONTACT PRIMARY KEY (CONTACT_ID),
    CONSTRAINT FK_CONTACT_PERSON FOREIGN KEY (PERSON_ID)
        REFERENCES PERSON (PERSON_ID) ON DELETE CASCADE,
    CONSTRAINT UQ_PERSON_CONTACT UNIQUE (PERSON_ID, CONTACT_NO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE CLIENT (
    CLIENT_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    PERSON_ID BIGINT UNSIGNED NOT NULL,
    ACCOUNT_STATUS VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    DOB DATE,
    CONSTRAINT PK_CLIENT PRIMARY KEY (CLIENT_ID),
    CONSTRAINT UQ_CLIENT_PERSON UNIQUE (PERSON_ID),
    CONSTRAINT FK_CLIENT_PERSON FOREIGN KEY (PERSON_ID)
        REFERENCES PERSON (PERSON_ID) ON DELETE CASCADE,
    CONSTRAINT CK_CLIENT_STATUS CHECK
        (ACCOUNT_STATUS IN ('ACTIVE', 'INACTIVE', 'SUSPENDED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE CONSULTANT (
    CONSULTANT_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    PERSON_ID BIGINT UNSIGNED NOT NULL,
    SPECIALIZATION VARCHAR(150) NOT NULL,
    QUALIFICATION LONGTEXT NOT NULL,
    CONSTRAINT PK_CONSULTANT PRIMARY KEY (CONSULTANT_ID),
    CONSTRAINT UQ_CONSULTANT_PERSON UNIQUE (PERSON_ID),
    CONSTRAINT FK_CONSULTANT_PERSON FOREIGN KEY (PERSON_ID)
        REFERENCES PERSON (PERSON_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE AVAILABILITY_SLOT (
    SLOT_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    CONSULTANT_ID BIGINT UNSIGNED NOT NULL,
    SLOT_DATE DATE NOT NULL,
    START_TIME TIME NOT NULL,
    END_TIME TIME NOT NULL,
    SLOT_STATUS VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE',
    CONSTRAINT PK_AVAILABILITY_SLOT PRIMARY KEY (SLOT_ID),
    CONSTRAINT UQ_SLOT_CONSULTANT UNIQUE (SLOT_ID, CONSULTANT_ID),
    CONSTRAINT FK_SLOT_CONSULTANT FOREIGN KEY (CONSULTANT_ID)
        REFERENCES CONSULTANT (CONSULTANT_ID) ON DELETE CASCADE,
    CONSTRAINT CK_SLOT_TIME_ORDER CHECK (END_TIME > START_TIME),
    CONSTRAINT CK_SLOT_STATUS CHECK
        (SLOT_STATUS IN ('AVAILABLE', 'BOOKED', 'BLOCKED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE APPOINTMENT (
    APPOINTMENT_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    CLIENT_ID BIGINT UNSIGNED NOT NULL,
    CONSULTANT_ID BIGINT UNSIGNED NOT NULL,
    SLOT_ID BIGINT UNSIGNED NOT NULL,
    STATUS VARCHAR(20) NOT NULL DEFAULT 'REQUESTED',
    APPOINTMENT_MODE VARCHAR(10) NOT NULL,
    REASON LONGTEXT,
    REQUESTED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_APPOINTMENT PRIMARY KEY (APPOINTMENT_ID),
    CONSTRAINT UQ_APPOINTMENT_SLOT UNIQUE (SLOT_ID),
    CONSTRAINT FK_APPOINTMENT_CLIENT FOREIGN KEY (CLIENT_ID)
        REFERENCES CLIENT (CLIENT_ID),
    
    CONSTRAINT FK_APPOINTMENT_SLOT_CONS FOREIGN KEY
        (SLOT_ID, CONSULTANT_ID)
        REFERENCES AVAILABILITY_SLOT (SLOT_ID, CONSULTANT_ID),
    CONSTRAINT CK_APPOINTMENT_STATUS CHECK
        (STATUS IN ('REQUESTED', 'CONFIRMED', 'CANCELLED', 'COMPLETED')),
    CONSTRAINT CK_APPOINTMENT_MODE CHECK
        (APPOINTMENT_MODE IN ('ONLINE', 'OFFLINE'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE PRECONSULTATION_FORM (
    FORM_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    APPOINTMENT_ID BIGINT UNSIGNED NOT NULL,
    RESPONSES JSON NOT NULL,
    SUBMITTED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_PRECONSULTATION_FORM PRIMARY KEY (FORM_ID),
    CONSTRAINT UQ_PRECONSULT_APPOINTMENT UNIQUE (APPOINTMENT_ID),
    CONSTRAINT FK_PRECONSULT_APPOINTMENT FOREIGN KEY (APPOINTMENT_ID)
        REFERENCES APPOINTMENT (APPOINTMENT_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE UPLOADED_FILE (
    FILE_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    CLIENT_ID BIGINT UNSIGNED NOT NULL,
    APPOINTMENT_ID BIGINT UNSIGNED NOT NULL,
    FILE_NAME VARCHAR(255) NOT NULL,
    FILE_SIZE BIGINT UNSIGNED NOT NULL,
    FILE_PATH VARCHAR(1000) NOT NULL,
    UPLOADED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_UPLOADED_FILE PRIMARY KEY (FILE_ID),
    CONSTRAINT FK_FILE_CLIENT FOREIGN KEY (CLIENT_ID)
        REFERENCES CLIENT (CLIENT_ID) ON DELETE CASCADE,
    CONSTRAINT FK_FILE_APPOINTMENT FOREIGN KEY (APPOINTMENT_ID)
        REFERENCES APPOINTMENT (APPOINTMENT_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE CONSULTATION_SESSION (
    SESSION_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    APPOINTMENT_ID BIGINT UNSIGNED NOT NULL,
    SESSION_STATUS VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED',
    STARTED_AT DATETIME,
    ENDED_AT DATETIME,
    CONSTRAINT PK_CONSULTATION_SESSION PRIMARY KEY (SESSION_ID),
    CONSTRAINT UQ_SESSION_APPOINTMENT UNIQUE (APPOINTMENT_ID),
    CONSTRAINT FK_SESSION_APPOINTMENT FOREIGN KEY (APPOINTMENT_ID)
        REFERENCES APPOINTMENT (APPOINTMENT_ID),
    CONSTRAINT CK_SESSION_STATUS CHECK
        (SESSION_STATUS IN ('SCHEDULED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT CK_SESSION_TIME CHECK
        (ENDED_AT IS NULL OR (STARTED_AT IS NOT NULL AND ENDED_AT >= STARTED_AT))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE PRIVATE_NOTE (
    NOTE_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    CONSULTANT_ID BIGINT UNSIGNED NOT NULL,
    SESSION_ID BIGINT UNSIGNED NOT NULL,
    NOTE_TEXT LONGTEXT NOT NULL,
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_PRIVATE_NOTE PRIMARY KEY (NOTE_ID),
    CONSTRAINT FK_NOTE_CONSULTANT FOREIGN KEY (CONSULTANT_ID)
        REFERENCES CONSULTANT (CONSULTANT_ID) ON DELETE CASCADE,
    CONSTRAINT FK_NOTE_SESSION FOREIGN KEY (SESSION_ID)
        REFERENCES CONSULTATION_SESSION (SESSION_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE FEEDBACK (
    FEEDBACK_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    CLIENT_ID BIGINT UNSIGNED NOT NULL,
    SESSION_ID BIGINT UNSIGNED NOT NULL,
    RATING TINYINT UNSIGNED NOT NULL,
    COMMENT_TEXT LONGTEXT,
    SUBMITTED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_FEEDBACK PRIMARY KEY (FEEDBACK_ID),
    CONSTRAINT UQ_FEEDBACK_SESSION UNIQUE (SESSION_ID),
    CONSTRAINT FK_FEEDBACK_CLIENT FOREIGN KEY (CLIENT_ID)
        REFERENCES CLIENT (CLIENT_ID) ON DELETE CASCADE,
    CONSTRAINT FK_FEEDBACK_SESSION FOREIGN KEY (SESSION_ID)
        REFERENCES CONSULTATION_SESSION (SESSION_ID) ON DELETE CASCADE,
    CONSTRAINT CK_FEEDBACK_RATING CHECK (RATING BETWEEN 1 AND 5)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE RESOURCE_QUERY (
    QUERY_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    CLIENT_ID BIGINT UNSIGNED NOT NULL,
    QUERY_TEXT LONGTEXT NOT NULL,
    QUERY_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_RESOURCE_QUERY PRIMARY KEY (QUERY_ID),
    CONSTRAINT FK_QUERY_CLIENT FOREIGN KEY (CLIENT_ID)
        REFERENCES CLIENT (CLIENT_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE RESOURCE_DOCUMENT (
    RESOURCE_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    TITLE VARCHAR(255) NOT NULL,
    CATEGORY VARCHAR(100) NOT NULL,
    URL VARCHAR(1000),
    CONTENT LONGTEXT,
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_RESOURCE_DOCUMENT PRIMARY KEY (RESOURCE_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE AI_RESPONSE (
    AI_RESPONSE_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    QUERY_ID BIGINT UNSIGNED NOT NULL,
    RESPONSE_TEXT LONGTEXT NOT NULL,
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_AI_RESPONSE PRIMARY KEY (AI_RESPONSE_ID),
    CONSTRAINT FK_RESPONSE_QUERY FOREIGN KEY (QUERY_ID)
        REFERENCES RESOURCE_QUERY (QUERY_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE AI_RESPONSE_RESOURCE_DOCUMENT (
    AI_RESPONSE_ID BIGINT UNSIGNED NOT NULL,
    RESOURCE_ID BIGINT UNSIGNED NOT NULL,
    CONSTRAINT PK_RESPONSE_RESOURCE PRIMARY KEY (AI_RESPONSE_ID, RESOURCE_ID),
    CONSTRAINT FK_ARRD_RESPONSE FOREIGN KEY (AI_RESPONSE_ID)
        REFERENCES AI_RESPONSE (AI_RESPONSE_ID) ON DELETE CASCADE,
    CONSTRAINT FK_ARRD_RESOURCE FOREIGN KEY (RESOURCE_ID)
        REFERENCES RESOURCE_DOCUMENT (RESOURCE_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE CONSULTANT_RESOURCE_DOCUMENT (
    CONSULTANT_ID BIGINT UNSIGNED NOT NULL,
    RESOURCE_ID BIGINT UNSIGNED NOT NULL,
    CURATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_CONSULTANT_RESOURCE PRIMARY KEY (CONSULTANT_ID, RESOURCE_ID),
    CONSTRAINT FK_CRD_CONSULTANT FOREIGN KEY (CONSULTANT_ID)
        REFERENCES CONSULTANT (CONSULTANT_ID) ON DELETE CASCADE,
    CONSTRAINT FK_CRD_RESOURCE FOREIGN KEY (RESOURCE_ID)
        REFERENCES RESOURCE_DOCUMENT (RESOURCE_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE INDEX IDX_APPT_CONSULTANT ON APPOINTMENT (CONSULTANT_ID);
CREATE INDEX IDX_NOTE_SESSION ON PRIVATE_NOTE (SESSION_ID);
CREATE INDEX IDX_NOTE_CONSULTANT ON PRIVATE_NOTE (CONSULTANT_ID);
CREATE INDEX IDX_FEEDBACK_CLIENT ON FEEDBACK (CLIENT_ID);
CREATE INDEX IDX_ARRD_RESOURCE ON AI_RESPONSE_RESOURCE_DOCUMENT (RESOURCE_ID);
CREATE INDEX IDX_CRD_RESOURCE ON CONSULTANT_RESOURCE_DOCUMENT (RESOURCE_ID);
